    <script>
        const btnFeedbackNext = document.querySelector('#btn-feedback-next');
        const btnFeedbackPrev = document.querySelector('#btn-feedback-prev');


        btnFeedbackNext.addEventListener('click', (e) => {
            const feedbackContainer = e.currentTarget.parentElement.nextElementSibling;
            feedbackContainer.scrollBy({
                left: 300,
                behavior: 'smooth'
            })
            let maxWidth = feedbackContainer.scrollWidth - feedbackContainer.clientWidth;
            const currentScrollLeft = 300 + Math.ceil(feedbackContainer.scrollLeft);
            if ( currentScrollLeft > maxWidth) {
                btnFeedbackNext.disabled = true;
            }
            btnFeedbackPrev.disabled = false;
        })
        btnFeedbackPrev.addEventListener('click', (e) => {
            const feedbackContainer = e.currentTarget.parentElement.nextElementSibling;
            feedbackContainer.scrollBy({
                left: -300,
                behavior: 'smooth'
            })
            if (feedbackContainer.scrollLeft <= 300) {
                btnFeedbackPrev.disabled = true;
            }
            btnFeedbackNext.disabled = false
        })
    </script>
@endsection